const assert = require('node:assert/strict');
const {clean, stats, scale, validateSession, fields} = require('../docs/core.js');
const sample={voltage:230,current:.08,power:12.4,energy:.012,frequency:50,powerFactor:.67,sensorOk:true};
assert.equal(clean(sample).quality.length,0);
const zeros=Object.fromEntries(fields.map(([k])=>[k,0]));
assert.equal(clean(zeros).quality.length,0);
assert.equal(clean({...sample,sensorOk:false}).power,null);
assert.equal(clean({...sample,powerFactor:1.1}).powerFactor,null);
assert.equal(clean({...sample,power:'12'}).power,null);
const measured=(s,p)=>({timestamp:new Date(s*1000).toISOString(),power:p});
assert.equal(stats([measured(0,3600),measured(1,3600)]).wh,1);
assert.equal(stats([measured(0,3600),measured(8,3600)]).wh,0);
assert.equal(stats([measured(0,null)]).peak,null);
const fitted=scale([59.9,60,60.1],'power','fit',1);
assert.ok(fitted.max-fitted.min<1);
assert.ok(fitted.min<=59.9&&fitted.max>=60.1);
const zoomed=scale([59.9,60,60.1],'power','fit',4);
assert.ok(zoomed.max-zoomed.min<fitted.max-fitted.min);
assert.ok(zoomed.clipped>0);
assert.equal(scale([60],'power','zero',1).min,0);
assert.ok(scale([0],'power','fit',64).max>0);
assert.ok(Number.isFinite(scale([],'current').max));
const session={schemaVersion:1,id:'example',appliance:'Fan',source:'serial',startedAt:'2026-10-22T00:00:00Z',endedAt:'2026-10-22T00:00:01Z',readings:[{...sample,timestamp:'2026-10-22T00:00:00Z'}],notes:[],analysis:[]};
assert.equal(validateSession(session).readings[0].power,12.4);
assert.throws(()=>validateSession({...session,source:'unknown'}));
assert.throws(()=>validateSession({...session,readings:[{}]}));
console.log('PASS: measurement validity, zero handling, sensor errors, energy gaps, graph fitting/zoom, session imports.');
